import { readFile, writeFile, mkdir } from 'node:fs/promises';
const strip = value => value.replace(/^import .*;\r?\n/gm, '').replace(/^export /gm, '');
const auth = strip(await readFile('src/services/pin-auth.js', 'utf8')).replace('const text = new TextEncoder();', 'const text = { encode: value => value };');
const sources = [auth, strip(await readFile('src/services/perspective.js', 'utf8')), strip(await readFile('src/services/dashboard-domain.js', 'utf8')), strip(await readFile('src/data/open-questions.js', 'utf8')), await readFile('apps-script/server/Server.js', 'utf8')];
await mkdir('apps-script/production', { recursive: true });
// Apps Script web handlers must return TextOutput synchronously. Server hashes,
// storage and locking are synchronous; the shared authentication rules can be
// emitted without async/await while browser stores retain their async API.
const bundle = sources.join('\n\n').replace(/\basync\s+/g, '').replace(/\bawait\s+/g, '');
await writeFile('apps-script/production/Code.gs', '// Generated by npm run build:server. Install this file only.\n' + bundle);
console.log('Built apps-script/production/Code.gs');
